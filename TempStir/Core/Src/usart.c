/* 工程使用 ARMCC 标准 C 库，通过 __use_no_semihosting 屏蔽 semihosting，
   并实现文件 I/O 桩，把标准输出(stdout)导向 USART1（PA9/TX，115200，8N1）。
   注意：仅重定向输出，不做输入；HAL_UART_Transmit 为阻塞发送。 */
#include <stdio.h>
#include <rt_sys.h>

#pragma import(__use_no_semihosting)

struct __FILE { int handle; };
FILE __stdout;
